#!/usr/bin/env python3
"""Test script to verify issue and PR linking functionality"""

import sys


def test_pr_body_with_issue_reference():
    """Test that PR body includes issue reference when issue_number is provided"""

    # Test 1: PR body should include issue reference
    issue_number = 10
    base_body = "Generated by script"

    # Simulate what happens in open_pr
    expected_body = f"Implements #{issue_number}\n\n{base_body}"

    # Verify the format
    assert f"#{issue_number}" in expected_body
    assert "Implements" in expected_body
    assert base_body in expected_body

    print(f"✓ Test 1 passed: PR body includes issue reference")
    print(f"  Expected body: {expected_body}")

    # Test 2: PR body without issue number
    expected_body_without = base_body
    assert f"#" not in expected_body_without
    print(f"✓ Test 2 passed: PR body without issue reference works correctly")


def test_pr_comment_format():
    """Test that PR comment format is correct"""

    pr_url = "https://github.com/PavelLiakh/ai-dev/pull/29"
    pr_number = pr_url.split("/")[-1]

    expected_comment = f"PR opened: #{pr_number}"

    assert pr_number == "29"
    assert expected_comment == "PR opened: #29"

    print(f"✓ Test 3 passed: PR comment format is correct")
    print(f"  Expected comment: {expected_comment}")


if __name__ == "__main__":
    print("Testing issue and PR linking functionality...\n")

    try:
        test_pr_body_with_issue_reference()
        test_pr_comment_format()

        print("\n✅ All tests passed!")
        sys.exit(0)
    except AssertionError as e:
        print(f"\n❌ Test failed: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"\n❌ Unexpected error: {e}")
        sys.exit(1)
