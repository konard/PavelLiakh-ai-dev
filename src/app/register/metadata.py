from functools import lru_cache

import pandas as pd
import json

from src.ioc import user_file_service
from src.config import config


@lru_cache(maxsize=1)
def get_metadata():
    # Загрузка CSV-файла (новый датасет, с русскими заголовками)
    data_file = user_file_service.get_current_file_path()
    df = pd.read_csv(data_file, encoding="utf-8")

    # Преобразуем столбец 'Дата' в формат datetime
    df["Дата"] = pd.to_datetime(df["Дата"], errors="coerce")

    # --- Колонки, связанные с датой ---
    df["Год"] = df["Дата"].dt.year
    df["Месяц"] = df["Дата"].dt.month
    df["День недели"] = df[
        "Дата"
    ].dt.day_name()  # день недели (на английском, если не задана локаль)
    df["Квартал"] = df["Дата"].dt.quarter

    # --- Расчет выручки, себестоимости и маржи заказа---
    df["Общая выручка заказа"] = (df["Цена"] * df["Количество"]).round(2)
    df["Общая себестоимость заказа"] = (df["Себестоимость"] * df["Количество"]).round(2)
    df["Маржа заказа"] = (df["Общая выручка заказа"] - df["Общая себестоимость заказа"]).round(2)

    # --- Показатель рентабельности ---
    df["Рентабельность"] = df.apply(
        lambda row: (
            round((row["Маржа заказа"] / row["Общая выручка заказа"] * 100), 2)
            if row["Общая выручка заказа"] != 0
            else 0
        ),
        axis=1,
    )

    # Сохранение обновленного датасета в CSV-файл
    df.to_csv(user_file_service.get_current_file_path(), index=False, encoding="utf-8")

    # Определение диапазона дат
    min_date = df["Дата"].min()
    max_date = df["Дата"].max()
    date_range = {
        "start_date": min_date.strftime("%Y-%m-%d") if pd.notnull(min_date) else None,
        "end_date": max_date.strftime("%Y-%m-%d") if pd.notnull(max_date) else None,
    }

    # Определение диапазона номеров заказов
    first_order = int(df["Номер заказа"].min())
    last_order = int(df["Номер заказа"].max())

    # --- Метаданные для каждого столбца ---
    metadata = {
        "Дата": "Дата заказа (формат YYYY-MM-DD).",
        "Номер заказа": "Порядковый номер заказа.",
        "Клиент": "Название компании, осуществившей покупку.",
        "Продукт": "Наименование продукта.",
        "Категория Продукта": "Категория продукта.",
        "Цена": "Цена продукта, в рублях.",
        "Себестоимость": "Себестоимость продукта.",
        "Количество": "Количество проданных единиц.",
        "Город": "Город, где была совершена продажа.",
        "Магазин": "Название магазина или точки продажи.",
        "Продавец": "Имя продавца.",
        "Способ оплаты": "Способ оплаты.",
        "Год": "Год заказа, извлеченный из колонки 'Дата'.",
        "Месяц": "Месяц заказа, извлеченный из колонки 'Дата'.",
        "День недели": "День недели заказа, извлеченный из колонки 'Дата'.",
        "Квартал": "Квартал года, извлеченный из колонки 'Дата'.",
        "Общая выручка заказа": "Общая выручка (Цена * Количество), округлена до двух знаков.",
        "Общая себестоимость заказа": "Общая себестоимость (Себестоимость * Количество), округлена до двух знаков.",
        "Маржа заказа": "Прибыль от заказа (Общая выручка - Общая себестоимость), округлена до двух знаков; равна 0, если заказ отменен.",
        "Рентабельность": "Рентабельность продажи в процентах (Прибыль / Общая выручка * 100), округлена до двух знаков.",
        "date_range": f"Даты начала и конца датасета: {date_range['start_date']} - {date_range['end_date']}",
        "order_range": f"Номера заказов в датасете: {first_order} - {last_order}",
    }

    # --- Добавление уникальных значений для некоторых колонок ---
    unique_values = {
        "Клиент": sorted(df["Клиент"].dropna().unique().tolist()),
        "Продукт": sorted(df["Продукт"].dropna().unique().tolist()),
        "Категория Продукта": sorted(df["Категория Продукта"].dropna().unique().tolist()),
        "Город": sorted(df["Город"].dropna().unique().tolist()),
        "Магазин": sorted(df["Магазин"].dropna().unique().tolist()),
        "Продавец": sorted(df["Продавец"].dropna().unique().tolist()),
        "Способ оплаты": sorted(df["Способ оплаты"].dropna().unique().tolist()),
    }

    metadata["unique_values"] = unique_values

    print(f"Generated metadata: {metadata}")

    return json.dumps(metadata, ensure_ascii=False, indent=4)


if __name__ == "__main__":
    metadata = get_metadata()
    print(metadata)
